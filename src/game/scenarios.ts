export const SCENARIOS: Scenario[] = [shieldScenario, deathScenario, delayScenario]

export function getScenario(id: string): Scenario {
  const found = SCENARIOS.find((s) => s.id === id)
  if (!found) throw new Error(`未知样例: ${id}`)
  return found
}

export function scenarioPlan(scenario: Scenario): Plan {
  const plan: Plan = {}
  for (const [id, command] of Object.entries(scenario.initialPlan)) {
    plan[id] = command ? { ...command } : null
  }
  return plan
}
