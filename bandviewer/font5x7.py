GLYPH_W = 5
GLYPH_H = 7
GLYPH_ADVANCE = 6  # 5 个像素 + 1 个像素间距


def text_width(text: str, scale: int = 1) -> int:
    """文本渲染后的像素宽度。"""
    return max(0, (len(text) * GLYPH_ADVANCE - 1) * scale)


def draw_text(
    gray: np.ndarray,
    x: int,
    y: int,
    text: str,
    scale: int = 1,
    value: float = 1.0,
) -> None:
    """在灰度图上原位绘制点阵文字（越界部分自动裁剪）。

    Parameters
    ----------
    gray: 待修改的二维浮点灰度数组，取值 [0, 1]。
    x, y: 左上角像素坐标。
    scale: 整数放大倍数，1 即真实 5x7 小字。
    value: 落笔像素的灰度值。
    """
    h, w = gray.shape
    cursor = x
    for ch in text.upper():
        glyph = GLYPHS.get(ch, GLYPHS[" "])
        for ry, row in enumerate(glyph):
            for rx, mark in enumerate(row):
                if mark != "#":
                    continue
                y0 = y + ry * scale
                x0 = cursor + rx * scale
                ys = slice(max(0, y0), min(h, y0 + scale))
                xs = slice(max(0, x0), min(w, x0 + scale))
                if ys.start < ys.stop and xs.start < xs.stop:
                    gray[ys, xs] = value
        cursor += GLYPH_ADVANCE * scale
