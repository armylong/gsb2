"""渲染用的固定颜色与阈值常量。

覆盖色刻意选择彼此差异大、且不会与自然灰度/植被配色混淆的颜色,
保证「被范围挤到同色的点」和特殊状态一眼可分。
"""

from __future__ import annotations

# RGBA (uint8)。覆盖在拉伸结果之上的特殊状态颜色。
NODATA_RGBA = (255, 0, 255, 255)      # 品红: 无值像素
LOW_CLIP_RGBA = (0, 200, 255, 255)    # 青: 被压到显示下界以下
HIGH_CLIP_RGBA = (255, 60, 60, 255)   # 红: 被顶到显示上界以上
LOW_DENOM_RGBA = (60, 60, 255, 255)   # 蓝: 归一化差值分母过小
CROSSHAIR_RGBA = (255, 255, 0, 255)   # 黄: 联动十字线
ROI_RGBA = (0, 255, 120, 255)         # 绿: 参考区框

# NDVI 色带 (低值红 -> 中值黄 -> 高值绿), 元素为 (value, (r,g,b))
NDVI_COLORMAP = (
    (-1.0, (180, 30, 30)),
    (-0.5, (220, 90, 40)),
    (0.0, (235, 220, 90)),
    (0.5, (110, 190, 90)),
    (1.0, (20, 120, 60)),
)

# 分母 |a + b| 小于该值时判定为分母过小 (可在界面调整)
DEFAULT_DENOM_EPS = 1e-6

# 渲染缓存上限 (字节), 防止超大图反复缓存占用内存
RENDER_CACHE_BYTES = 256 * 1024 * 1024
