PROTAN = "protan"
DEUTAN = "deutan"
KIND_LABELS = {PROTAN: "红色觉异常 (protan)", DEUTAN: "绿色觉异常 (deutan)"}


def _table(kind: str):
    if kind == PROTAN:
        return _PROTAN_TABLE
    if kind == DEUTAN:
        return _DEUTAN_TABLE
    raise ValueError(f"未知模拟类型: {kind!r}")


def simulation_matrix(kind: str, severity: float) -> np.ndarray:
    """返回指定类型与程度 (0.0-1.0) 的 3x3 模拟矩阵, 表间线性插值。"""
    severity = float(np.clip(severity, 0.0, 1.0))
    table = _table(kind)
    for i in range(len(table) - 1):
        s0, m0 = table[i]
        s1, m1 = table[i + 1]
        if s0 <= severity <= s1:
            t = 0.0 if s1 == s0 else (severity - s0) / (s1 - s0)
            return m0 * (1.0 - t) + m1 * t
    return table[-1][1].copy()


def simulate(rgb, kind: str, severity: float) -> np.ndarray:
    """对 sRGB(0-255) 数组做色觉模拟, alpha 不参与。返回同形状浮点数组。

    Machado 矩阵定义在归一化 (0-1) sRGB 上, 这里内部做缩放。
    """
    arr = np.asarray(rgb, dtype=float)
    matrix = simulation_matrix(kind, severity)
    out = (arr / 255.0) @ matrix.T
    return np.clip(out, 0.0, 1.0) * 255.0
